void Driver::printHelp(std::ostream &output)
{
    printCompilerBanner(output);
    printHelpUsagePart1(output);
    printHelpUsagePart2(output);
    printHelpUsagePart3(output);
    printHelpUsagePart4(output);
    if (activeCompilerLanguage() == CompilerLanguage::Spanish)
    {
        printHelpSpanishPart1(output);
        return;
    }
    printHelpEnglishPart1(output);
    printHelpEnglishPart2(output);
}

